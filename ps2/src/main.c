static const char *main_items[] = {
    "Memory card slot 1",
    "Memory card slot 2",
    "Network server (desktop app)",
    "Restore from USB",
    "Restore from SMB share",
    "MemCard PRO2 / SD2PSX (MMCE)",
    "About / settings",
    "Exit to browser",
};

static void main_item(int i, char *out, int n, void *c)
{
    (void)c;
    snprintf(out, n, "%s", main_items[i]);
}

int main(int argc, char *argv[])
{
    if (argc > 0 && argv[0]) {
        strncpy(g_boot_dir, argv[0], sizeof(g_boot_dir) - 1);
        char *slash = strrchr(g_boot_dir, '/');
        if (!slash)
            slash = strrchr(g_boot_dir, ':');
        if (slash)
            slash[1] = 0;
        else
            g_boot_dir[0] = 0;
    }
    reset_iop();
    ui_init();
    config_defaults(&g_cfg);
    init_all();

    int cursor = 0;
    for (;;) {
        int sel = ui_list("main menu", "X: select", 8, main_item, NULL, &cursor, BTN_CROSS, NULL);
        switch (sel) {
            case 0: card_browser(0); break;
            case 1: card_browser(1); break;
            case 2: server_screen(); break;
            case 3: restore_browser(TARGET_USB); break;
            case 4: restore_browser(TARGET_SMB); break;
            case 5: mmce_screen(); break;
            case 6:
                ui_message("About",
                           "PS2 Save Manager %s\n\nIP: %s (%s)  port %d\nSMB: %s %s\nBackups: mass:/%s and smb:/%s\n\n"
                           "Settings are read from PS2SM.CNF next to the ELF,\nmc0:/PS2SM/PS2SM.CNF or mass:/PS2SM/PS2SM.CNF.",
                           PS2SM_VERSION, g_ip_str, g_cfg.use_dhcp ? "DHCP" : "static", g_cfg.port,
                           g_cfg.smb_ip[0] ? g_cfg.smb_ip : "(not set)", g_cfg.smb_share, PS2SM_DIR,
                           g_cfg.smb_dir);
                break;
            case 7:
                if (ui_confirm("Exit to the PS2 browser?")) {
                    fileXioExit();
                    SifExitRpc();
                    LoadExecPS2("rom0:OSDSYS", 0, NULL);
                }
                break;
            default: break;
        }
    }
    return 0;
}
