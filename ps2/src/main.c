static int load(const char *name, unsigned char *irx, unsigned int size, int argc_len, const char *args)
{
    int ret = 0;
    int id = SifExecModuleBuffer(irx, size, argc_len, args, &ret);
    if (id < 0 || ret == 1 /* NO_RESIDENT_END */) {
        printf("PS2SM: %s failed (%d/%d)\n", name, id, ret);
        return -1;
    }
    return 0;
}
#define LOAD(n) load(#n, n##_irx, size_##n##_irx, 0, NULL)

static void reset_iop(void)
{
    SifInitRpc(0);
    while (!SifIopReset("", 0))
        ;
    while (!SifIopSync())
        ;
    SifInitRpc(0);
    SifLoadFileInit();
    SifInitIopHeap();
    sbv_patch_enable_lmb();
    sbv_patch_disable_prefix_check();
}

static void boot_progress(const char *msg)
{
    ui_status("%s", msg);
}

static void init_all(void)
{
    ui_header("starting");
    ui_line(1, 0, "Loading I/O modules...");
    LOAD(iomanX);
    LOAD(fileXio);
    fileXioInit();
    LOAD(sio2man);
    LOAD(mcman);
    LOAD(mcserv);
    mcio_init();
    LOAD(padman);
    ui_pad_init();

    g_have_mmce = LOAD(mmceman) == 0;

    ui_line(2, 0, "USB mass storage...");
    g_have_usb = LOAD(usbd) == 0 && LOAD(bdm) == 0 && LOAD(bdmfs_fatfs) == 0 && LOAD(usbmass_bd) == 0;
    DelayThread(500 * 1000); /* let a stick enumerate */

    config_load(&g_cfg);

    ui_line(3, 0, "Network (%s)...", g_cfg.use_dhcp ? "DHCP" : g_cfg.ip);
    LOAD(poweroff);
    int net_ok = LOAD(ps2dev9) == 0 && LOAD(netman) == 0 && LOAD(smap) == 0;
    if (net_ok) {
        char args[64];
        int alen;
        if (g_cfg.use_dhcp) {
            static const char dummy[] = "169.254.0.1\0" "255.255.0.0\0" "0.0.0.0";
            memcpy(args, dummy, sizeof(dummy));
            alen = sizeof(dummy);
        } else {
            alen = snprintf(args, sizeof(args), "%s%c%s%c%s", g_cfg.ip, 0, g_cfg.netmask, 0, g_cfg.gateway) + 1;
        }
        net_ok = load("ps2ip-nm", ps2ip_nm_irx, size_ps2ip_nm_irx, alen, args) == 0 && LOAD(ps2ips) == 0;
        if (net_ok)
            net_ok = net_init(boot_progress) == 0;
        if (net_ok)
            LOAD(smbman);
    }
    if (net_ok && g_cfg.smb_ip[0]) {
        char err[96];
        ui_line(4, 0, "SMB share \\\\%s\\%s...", g_cfg.smb_ip, g_cfg.smb_share);
        if (smb_connect(err, sizeof(err)) < 0)
            ui_status("%s", err);
    }
}

