/* MMCE                                                                 */

static void mmce_screen(void)
{
    int port = 0;
    for (;;) {
        ui_header("MemCard PRO2 / SD2PSX (MMCE)");
        for (int p = 0; p < 2; p++) {
            int card = 0, ch = 0;
            char gid[64];
            if (mmce_get(p, &card, &ch, gid, sizeof(gid)) == 0)
                ui_line(1 + p * 2, p == port, "Slot %d: card %d  channel %d  %s", p + 1, card, ch, gid);
            else
                ui_line(1 + p * 2, p == port, "Slot %d: no MMCE device", p + 1);
        }
        ui_line(7, 0, "L1/R1: previous/next card   L2/R2: previous/next channel");
        ui_line(8, 0, "Up/Down: choose slot");
        ui_footer("O: back");
        for (;;) {
            u32 b = ui_buttons();
            if (!b)
                continue;
            if (b & BTN_CIRCLE)
                return;
            if (b & (BTN_UP | BTN_DOWN))
                port ^= 1;
            else if (b & BTN_L1)
                mmce_set(port, 0, 2, 0);
            else if (b & BTN_R1)
                mmce_set(port, 0, 1, 0);
            else if (b & BTN_L2)
                mmce_set(port, 1, 2, 0);
            else if (b & BTN_R2)
                mmce_set(port, 1, 1, 0);
            else
                continue;
            if (b & (BTN_L1 | BTN_R1 | BTN_L2 | BTN_R2))
                DelayThread(1200 * 1000); /* card needs a moment */
            break;
        }
    }
}

