/* Network server                                                       */

static void server_screen(void)
{
    if (!g_have_net) {
        ui_message("Network", "The network is not up.\nCheck the cable, or set a static IP in PS2SM.CNF:\n  ip=192.168.1.50\n  netmask=255.255.255.0\n  gateway=192.168.1.1");
        return;
    }
    if (net_server_start(g_cfg.port) < 0) {
        ui_message("Network", "Cannot listen on port %d.", g_cfg.port);
        return;
    }
    int last_req = -1;
    char last_msg[96] = "";
    int tick = 0;
    for (;;) {
        if (last_req != g_net_requests || strcmp(last_msg, g_net_last) || tick == 0) {
            ui_header("network server");
            ui_line(1, 0, "Connect the desktop app to:");
            ui_line(3, 1, "%s   port %d", g_ip_str, g_cfg.port);
            ui_line(5, 0, "Status:   %s", g_net_status);
            ui_line(6, 0, "Requests: %d", g_net_requests);
            ui_line(7, 0, "Last:     %s", g_net_last);
            ui_line(9, 0, "Leave this screen open while transferring.");
            ui_footer("O: stop server and go back");
            last_req = g_net_requests;
            strcpy(last_msg, g_net_last);
        }
        tick = (tick + 1) % 1000;
        net_server_poll(30);
        if (ui_buttons() & BTN_CIRCLE)
            break;
    }
    net_server_stop();
}

