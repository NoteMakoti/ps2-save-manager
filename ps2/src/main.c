/* Restore                                                              */

typedef struct
{
    char **names;
    int count;
} names_ctx_t;

static void name_item(int i, char *out, int n, void *c)
{
    names_ctx_t *s = c;
    snprintf(out, n, "%s", s->names[i]);
}

static const char *slot_items[] = {"Memory card slot 1", "Memory card slot 2"};

static void slot_item(int i, char *out, int n, void *c)
{
    (void)c;
    snprintf(out, n, "%s", slot_items[i]);
}

static void restore_browser(target_t t)
{
    if (t == TARGET_SMB && !g_have_smb) {
        char err[96];
        if (smb_connect(err, sizeof(err)) < 0) {
            ui_message("SMB", "Cannot connect to the SMB share:\n%s", err);
            return;
        }
    }
    if (!storage_available(t)) {
        ui_message("Restore", "%s is not available.", storage_name(t));
        return;
    }
    int cursor = 0;
    for (;;) {
        names_ctx_t ctx;
        storage_list_psu(t, &ctx.names, &ctx.count);
        char root[160], title[200];
        storage_root(t, root, sizeof(root));
        snprintf(title, sizeof(title), "Restore from %s", root);
        int sel = ui_list(title, "X: restore to a card  O: back", ctx.count, name_item, &ctx, &cursor, BTN_CROSS, NULL);
        if (sel < 0) {
            storage_free_list(ctx.names, ctx.count);
            return;
        }
        char file[256];
        snprintf(file, sizeof(file), "%s", ctx.names[sel]);
        storage_free_list(ctx.names, ctx.count);

        int scur = 0;
        int port = ui_list(file, "X: restore here  O: back", 2, slot_item, NULL, &scur, BTN_CROSS, NULL);
        if (port < 0)
            continue;
        u8 *data;
        int len;
        ui_status("Reading %s...", file);
        if (storage_read(t, file, &data, &len) < 0) {
            ui_message("Restore", "Cannot read %s.", file);
            continue;
        }
        char dir[40] = "";
        ui_status("Writing to slot %d...", port + 1);
        int r = mcio_psu_to_card(port, data, len, 0, dir);
        if (r == -1001 && ui_confirm("%s already exists in slot %d. Overwrite?", dir, port + 1))
            r = mcio_psu_to_card(port, data, len, 1, dir);
        free(data);
        if (r == 0)
            ui_message("Restore", "Restored %s to slot %d.", dir, port + 1);
        else if (r == sceMcResFullDevice)
            ui_message("Restore", "Not enough free space in slot %d.", port + 1);
        else if (r == -1000)
            ui_message("Restore", "%s is not a valid .psu file.", file);
        else if (r != -1001)
            ui_message("Restore", "Restore failed (%d).", r);
    }
}

