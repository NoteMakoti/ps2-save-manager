/* Card browser                                                         */

typedef struct
{
    save_info_t *saves;
    int count;
} saves_ctx_t;

static void save_item(int i, char *out, int n, void *c)
{
    saves_ctx_t *s = c;
    save_info_t *si = &s->saves[i];
    snprintf(out, n, "%-20.20s %5uK  %.40s", si->name, (unsigned)((si->size + 1023) / 1024), si->title);
}

static int backup_save(int port, const char *dir, target_t t)
{
    buf_t b;
    buf_init(&b);
    ui_status("Reading %s...", dir);
    int r = mcio_save_to_psu(port, dir, &b);
    if (r == 0) {
        char name[48];
        snprintf(name, sizeof(name), "%s.psu", dir);
        ui_status("Writing %s to %s...", name, storage_name(t));
        r = storage_write(t, name, b.data, b.len);
    }
    buf_free(&b);
    return r;
}

static int copy_save(int from, const char *dir, int to)
{
    buf_t b;
    buf_init(&b);
    ui_status("Reading %s...", dir);
    int r = mcio_save_to_psu(from, dir, &b);
    if (r == 0) {
        ui_status("Writing to slot %d...", to + 1);
        r = mcio_psu_to_card(to, b.data, b.len, 0, NULL);
        if (r == -1001 && ui_confirm("%s exists in slot %d. Overwrite?", dir, to + 1))
            r = mcio_psu_to_card(to, b.data, b.len, 1, NULL);
    }
    buf_free(&b);
    return r;
}

static const char *action_items[] = {"Back up to USB", "Back up to SMB share", "Copy to the other slot", "Delete", "Details"};

static void action_item(int i, char *out, int n, void *c)
{
    (void)c;
    snprintf(out, n, "%s", action_items[i]);
}

static void card_browser(int port)
{
    int cursor = 0;
    for (;;) {
        mc_info_t mi;
        mcio_info(port, &mi);
        if (!mi.present) {
            ui_message("Memory card", "No memory card in slot %d.", port + 1);
            return;
        }
        if (mi.type != sceMcTypePS2) {
            ui_message("Memory card", "The card in slot %d is not a PS2 card (type %d).", port + 1, mi.type);
            return;
        }
        if (!mi.formatted) {
            if (ui_confirm("Card in slot %d is unformatted. Format it now?", port + 1)) {
                ui_status("Formatting...");
                mcio_format(port);
                continue;
            }
            return;
        }
        saves_ctx_t ctx = {0, 0};
        ui_header("reading card");
        ui_status("Reading saves...");
        mcio_list_saves(port, &ctx.saves, &ctx.count);
        char title[64];
        snprintf(title, sizeof(title), "Slot %d - %d saves - %d KB free", port + 1, ctx.count, mi.free_kb);
        u32 pressed = 0;
        int sel = ui_list(title, "X: actions  TRIANGLE: all->USB  SQUARE: all->SMB  START: refresh  O: back", ctx.count,
                          save_item, &ctx, &cursor, BTN_CROSS | BTN_TRIANGLE | BTN_SQUARE | BTN_START, &pressed);
        if (sel < 0 && !(pressed & (BTN_TRIANGLE | BTN_SQUARE | BTN_START))) {
            free(ctx.saves);
            return;
        }
        if (pressed & BTN_START) {
            free(ctx.saves);
            continue;
        }
        if (pressed & (BTN_TRIANGLE | BTN_SQUARE)) {
            target_t t = (pressed & BTN_TRIANGLE) ? TARGET_USB : TARGET_SMB;
            if (!storage_available(t))
                ui_message("Backup", "%s is not available.", storage_name(t));
            else if (ui_confirm("Back up all %d saves to %s?", ctx.count, storage_name(t))) {
                int ok = 0;
                for (int i = 0; i < ctx.count; i++)
                    ok += backup_save(port, ctx.saves[i].name, t) == 0;
                ui_message("Backup", "%d of %d saves backed up to %s.", ok, ctx.count, storage_name(t));
            }
            free(ctx.saves);
            continue;
        }
        save_info_t si = ctx.saves[sel];
        free(ctx.saves);

        int acur = 0;
        char atitle[64];
        snprintf(atitle, sizeof(atitle), "%s", si.name);
        int a = ui_list(atitle, "X: select  O: back", 5, action_item, NULL, &acur, BTN_CROSS, NULL);
        int r = 0;
        switch (a) {
            case 0:
            case 1: {
                target_t t = a == 0 ? TARGET_USB : TARGET_SMB;
                if (!storage_available(t)) {
                    ui_message("Backup", "%s is not available.", storage_name(t));
                    break;
                }
                r = backup_save(port, si.name, t);
                ui_message("Backup", r == 0 ? "Saved %s.psu to %s." : "Backup of %s to %s failed.", si.name, storage_name(t));
                break;
            }
            case 2:
                r = copy_save(port, si.name, 1 - port);
                if (r != -1001)
                    ui_message("Copy", r == 0 ? "Copied %s to slot %d." : "Copy of %s to slot %d failed.", si.name, 2 - port);
                break;
            case 3:
                if (ui_confirm("Delete %s? This cannot be undone.", si.name)) {
                    char p[48];
                    snprintf(p, sizeof(p), "/%s", si.name);
                    r = mcio_delete_tree(port, p);
                    if (r < 0)
                        ui_message("Delete", "Delete failed (%d).", r);
                }
                break;
            case 4: {
                const u8 *m = si.modified;
                ui_message("Details", "Directory: %s\nTitle:     %s\nSize:      %u bytes\nModified:  %04d-%02d-%02d %02d:%02d\nMode:      %04x",
                           si.name, si.title, (unsigned)si.size, m[6] | (m[7] << 8), m[5], m[4], m[3], m[2], si.mode);
                break;
            }
        }
    }
}

